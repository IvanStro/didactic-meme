CREATE TABLE IF NOT EXISTS web_analytics_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  event_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  visitor_id VARCHAR(64) NOT NULL,
  session_id VARCHAR(64) NOT NULL,
  user_id INT NULL,
  event_name VARCHAR(64) NOT NULL,
  path VARCHAR(255) NOT NULL,
  source_channel VARCHAR(32) NOT NULL DEFAULT 'direct',
  referrer_host VARCHAR(191) NULL,
  utm_source VARCHAR(80) NULL,
  utm_medium VARCHAR(80) NULL,
  utm_campaign VARCHAR(120) NULL,
  utm_term VARCHAR(120) NULL,
  utm_content VARCHAR(120) NULL,
  gclid VARCHAR(180) NULL,
  device_type VARCHAR(16) NOT NULL DEFAULT 'desktop',
  country_code CHAR(2) NULL,
  lang VARCHAR(20) NULL,
  tz VARCHAR(64) NULL,
  ip_hash CHAR(64) NULL,
  user_agent VARCHAR(255) NULL,
  props_json TEXT NULL,
  PRIMARY KEY (id),
  KEY idx_event_at (event_at),
  KEY idx_event_name_at (event_name, event_at),
  KEY idx_path_at (path, event_at),
  KEY idx_source_at (source_channel, event_at),
  KEY idx_device_at (device_type, event_at),
  KEY idx_country_at (country_code, event_at),
  KEY idx_visitor_at (visitor_id, event_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
