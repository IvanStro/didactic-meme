-- Trading efficiency analytics (daily snapshots + period reports + advice)
-- Apply: mysql ... < run/migrations/20260927_create_trading_analytics.sql

CREATE TABLE IF NOT EXISTS analytics_user_daily (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  snap_date DATE NOT NULL,
  user_id INT UNSIGNED NOT NULL,
  nickname VARCHAR(128) NULL,
  email VARCHAR(255) NULL,
  billing_status VARCHAR(32) NULL,
  pairs_running TINYINT UNSIGNED NOT NULL DEFAULT 0,
  pairs_paused TINYINT UNSIGNED NOT NULL DEFAULT 0,
  pairs_total TINYINT UNSIGNED NOT NULL DEFAULT 0,
  fba_sum_running DECIMAL(18,8) NOT NULL DEFAULT 0,
  fba_avg_running DECIMAL(18,8) NOT NULL DEFAULT 0,
  fba_min_running DECIMAL(18,8) NULL,
  fba_max_running DECIMAL(18,8) NULL,
  binance_usdt_free DECIMAL(18,8) NULL,
  binance_usdt_locked DECIMAL(18,8) NULL,
  inventory_mark_usdt DECIMAL(18,8) NULL COMMENT 'open positions mark-to-market',
  capital_total_usdt DECIMAL(18,8) NULL COMMENT 'free+locked USDT + inventory',
  deposit_inferred_usdt DECIMAL(18,8) NOT NULL DEFAULT 0 COMMENT 'day-over-day capital jump proxy',
  deposit_api_usdt DECIMAL(18,8) NULL COMMENT 'Binance deposit hisrec if available',
  realized_pnl_all DECIMAL(18,8) NOT NULL DEFAULT 0,
  realized_pnl_1d DECIMAL(18,8) NOT NULL DEFAULT 0,
  realized_pnl_7d DECIMAL(18,8) NOT NULL DEFAULT 0,
  realized_pnl_30d DECIMAL(18,8) NOT NULL DEFAULT 0,
  sells_1d INT UNSIGNED NOT NULL DEFAULT 0,
  sells_7d INT UNSIGNED NOT NULL DEFAULT 0,
  buys_1d INT UNSIGNED NOT NULL DEFAULT 0,
  open_subs_l5plus INT UNSIGNED NOT NULL DEFAULT 0,
  max_open_level INT UNSIGNED NOT NULL DEFAULT 0,
  fba_to_capital_pct DECIMAL(10,4) NULL COMMENT 'sum FBA running / capital * 100',
  risk_score TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0-100 higher=riskier',
  risk_flags_json JSON NULL,
  efficiency_score DECIMAL(10,4) NULL COMMENT 'realized_7d / max(capital,1) * 100',
  meta_json JSON NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_user_day (snap_date, user_id),
  KEY idx_snap (snap_date),
  KEY idx_eff (snap_date, efficiency_score)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS analytics_pair_daily (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  snap_date DATE NOT NULL,
  user_id INT UNSIGNED NOT NULL,
  strategy_id INT UNSIGNED NOT NULL,
  symbol VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL,
  fba DECIMAL(18,8) NOT NULL DEFAULT 0,
  open_qty DECIMAL(24,12) NOT NULL DEFAULT 0,
  avg_price DECIMAL(24,12) NOT NULL DEFAULT 0,
  mark_price DECIMAL(24,12) NULL,
  inventory_mark_usdt DECIMAL(18,8) NULL,
  unrealized_pnl_usdt DECIMAL(18,8) NULL,
  realized_pnl_all DECIMAL(18,8) NOT NULL DEFAULT 0,
  realized_pnl_1d DECIMAL(18,8) NOT NULL DEFAULT 0,
  realized_pnl_7d DECIMAL(18,8) NOT NULL DEFAULT 0,
  open_subs INT UNSIGNED NOT NULL DEFAULT 0,
  max_open_level INT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_pair_day (snap_date, strategy_id),
  KEY idx_user_day (snap_date, user_id),
  KEY idx_symbol_day (snap_date, symbol)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS analytics_report (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  period_type ENUM('week','month','year') NOT NULL,
  period_start DATE NOT NULL,
  period_end DATE NOT NULL,
  title VARCHAR(255) NOT NULL,
  summary_uk MEDIUMTEXT NOT NULL,
  body_uk MEDIUMTEXT NOT NULL,
  metrics_json JSON NULL,
  ranking_json JSON NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_period (period_type, period_start, period_end),
  KEY idx_type_end (period_type, period_end)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS analytics_advice (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  report_id BIGINT UNSIGNED NULL,
  scope ENUM('global','user','pair') NOT NULL DEFAULT 'global',
  user_id INT UNSIGNED NULL,
  symbol VARCHAR(32) NULL,
  advice_uk MEDIUMTEXT NOT NULL,
  priority TINYINT UNSIGNED NOT NULL DEFAULT 50,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_report (report_id),
  KEY idx_active (active, scope),
  CONSTRAINT fk_advice_report FOREIGN KEY (report_id) REFERENCES analytics_report(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
